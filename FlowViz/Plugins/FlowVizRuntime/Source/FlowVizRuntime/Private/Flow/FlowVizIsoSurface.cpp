/*
 * NAMED namespace: unity build (#37).
 *
 * The tables are Paul Bourke's canonical marching-cubes edge and triangle
 * tables -- the one piece of this file that is transcription rather than
 * design. The topology test (watertight sphere) is what checks the
 * transcription: a single wrong entry tears the surface at that case.
 */
namespace FlowVizIsoSurfaceLocal
{
	extern const int32 EdgeTable[256];
	extern const int8 TriTable[256][16];

	/** Cube corner offsets in the standard MC numbering. */
	const FIntVector CornerOffsets[8] = {
		FIntVector(0, 0, 0), FIntVector(1, 0, 0), FIntVector(1, 1, 0), FIntVector(0, 1, 0),
		FIntVector(0, 0, 1), FIntVector(1, 0, 1), FIntVector(1, 1, 1), FIntVector(0, 1, 1)
	};

	/** Edge -> its two corners, standard numbering. */
	const int32 EdgeCorners[12][2] = {
		{0, 1}, {1, 2}, {2, 3}, {3, 0},
		{4, 5}, {5, 6}, {6, 7}, {7, 4},
		{0, 4}, {1, 5}, {2, 6}, {3, 7}
	};

	int32 ValueIndex(const FIntVector& Counts, const FIntVector& Voxel)
	{
		return (Voxel.Z * Counts.Y + Voxel.Y) * Counts.X + Voxel.X;
	}

	/**
	 * The field gradient at a grid node, one-sided at the grid boundary and
	 * at NaN neighbours -- the P1 stencil policy inlined over plain arrays.
	 * Falls back to zero on a starved axis (the caller normalizes with a
	 * guard), which can only happen inside a NaN pocket no cube consumes.
	 */
	FVector GradientAt(
		const FlowVizIsoSurface::FIsoGrid& Grid, const FIntVector& Node)
	{
		FVector Gradient = FVector::ZeroVector;
		for (int32 Axis = 0; Axis < 3; ++Axis)
		{
			FIntVector Step = FIntVector::ZeroValue;
			Step[Axis] = 1;

			const FIntVector ForwardNode = Node + Step;
			const FIntVector BackwardNode = Node - Step;
			const bool bHasForward = ForwardNode[Axis] < Grid.Counts[Axis]
				&& FMath::IsFinite(Grid.Values[ValueIndex(Grid.Counts, ForwardNode)]);
			const bool bHasBackward = BackwardNode[Axis] >= 0
				&& FMath::IsFinite(Grid.Values[ValueIndex(Grid.Counts, BackwardNode)]);
			const double Here = Grid.Values[ValueIndex(Grid.Counts, Node)];
			const double H = Grid.Spacing[Axis];

			if (bHasForward && bHasBackward)
			{
				Gradient[Axis] =
					(Grid.Values[ValueIndex(Grid.Counts, ForwardNode)]
						- Grid.Values[ValueIndex(Grid.Counts, BackwardNode)])
					/ (2.0 * H);
			}
			else if (bHasForward)
			{
				Gradient[Axis] =
					(Grid.Values[ValueIndex(Grid.Counts, ForwardNode)] - Here) / H;
			}
			else if (bHasBackward)
			{
				Gradient[Axis] =
					(Here - Grid.Values[ValueIndex(Grid.Counts, BackwardNode)]) / H;
			}
		}
		return Gradient;
	}
}

bool FlowVizIsoSurface::ExtractIsoSurface(
	const FIsoGrid& Grid, double IsoValue, FFlowVizMeshSection& OutSection)
{
	using namespace FlowVizIsoSurfaceLocal;

	OutSection = FFlowVizMeshSection();
	if (!Grid.IsValid() || !FMath::IsFinite(IsoValue))
	{
		return false;
	}

	const FMatrix SolverToUnreal = MakeSolverToUnrealTransform();

	/*
	 * VERTEX WELDING BY EDGE KEY. An edge is identified by its lower grid
	 * node and its axis; every cube that shares the edge shares the vertex,
	 * which is what makes the surface watertight and the vertex count
	 * testably sub-soup.
	 */
	TMap<uint64, int32> EdgeVertexCache;
	auto EdgeKey = [&Grid](const FIntVector& Node, int32 Axis) -> uint64
	{
		const uint64 Linear = static_cast<uint64>(
			(Node.Z * Grid.Counts.Y + Node.Y) * Grid.Counts.X + Node.X);
		return Linear * 3 + Axis;
	};

	double CornerValues[8];
	FIntVector CornerNodes[8];

	for (int32 Z = 0; Z + 1 < Grid.Counts.Z; ++Z)
	{
		for (int32 Y = 0; Y + 1 < Grid.Counts.Y; ++Y)
		{
			for (int32 X = 0; X + 1 < Grid.Counts.X; ++X)
			{
				const FIntVector Base(X, Y, Z);

				// Gather corners; a NaN corner skips the cube whole -- the P1
				// mask policy. The obstacle's own surface is the patch mesh's
				// job, so a skipped cube is a hole in the FIELD surface only.
				uint32 CaseIndex = 0;
				bool bMasked = false;
				for (int32 Corner = 0; Corner < 8; ++Corner)
				{
					CornerNodes[Corner] = Base + CornerOffsets[Corner];
					CornerValues[Corner] =
						Grid.Values[ValueIndex(Grid.Counts, CornerNodes[Corner])];
					if (!FMath::IsFinite(CornerValues[Corner]))
					{
						bMasked = true;
						break;
					}
					if (CornerValues[Corner] < IsoValue)
					{
						CaseIndex |= (1u << Corner);
					}
				}
				if (bMasked || EdgeTable[CaseIndex] == 0)
				{
					continue;
				}

				// One shared vertex per crossed edge.
				int32 EdgeVertex[12] = { INDEX_NONE };
				for (int32 Edge = 0; Edge < 12; ++Edge)
				{
					if ((EdgeTable[CaseIndex] & (1 << Edge)) == 0)
					{
						continue;
					}
					const int32 CornerA = EdgeCorners[Edge][0];
					const int32 CornerB = EdgeCorners[Edge][1];
					const FIntVector& NodeA = CornerNodes[CornerA];
					const FIntVector& NodeB = CornerNodes[CornerB];

					// The edge's canonical identity: its lower node + axis.
					const FIntVector Delta = NodeB - NodeA;
					const int32 Axis = Delta.X != 0 ? 0 : (Delta.Y != 0 ? 1 : 2);
					const FIntVector LowNode =
						(Delta.X + Delta.Y + Delta.Z) > 0 ? NodeA : NodeB;
					const uint64 Key = EdgeKey(LowNode, Axis);

					if (const int32* Existing = EdgeVertexCache.Find(Key))
					{
						EdgeVertex[Edge] = *Existing;
						continue;
					}

					/*
					 * THE INTERPOLATED CROSSING -- the technique that makes
					 * tubes smooth. T is where the field equals IsoValue along
					 * the edge; the denominator cannot vanish because the edge
					 * is crossed (values straddle the level).
					 */
					const double ValueA = CornerValues[CornerA];
					const double ValueB = CornerValues[CornerB];
					const double T = (IsoValue - ValueA) / (ValueB - ValueA);

					const FVector SolverA = Grid.Origin
						+ FVector(NodeA.X * Grid.Spacing.X, NodeA.Y * Grid.Spacing.Y,
							NodeA.Z * Grid.Spacing.Z);
					const FVector SolverB = Grid.Origin
						+ FVector(NodeB.X * Grid.Spacing.X, NodeB.Y * Grid.Spacing.Y,
							NodeB.Z * Grid.Spacing.Z);
					const FVector SolverPosition = FMath::Lerp(SolverA, SolverB, T);

					// Normal: the gradient interpolated the same way, negated
					// (outward = toward decreasing field), mirrored as a
					// DIRECTION -- the position adapter would scale it.
					const FVector Gradient = FMath::Lerp(
						GradientAt(Grid, NodeA), GradientAt(Grid, NodeB), T);
					FVector SolverNormal = -Gradient;
					if (!SolverNormal.Normalize())
					{
						SolverNormal = FVector::ZAxisVector;
					}

					const int32 NewIndex = OutSection.Vertices.Num();
					OutSection.Vertices.Add(
						SolverToUnreal.TransformPosition(SolverPosition));
					OutSection.Normals.Add(
						FVector(SolverToUnrealDirection(FVector3f(SolverNormal))));
					EdgeVertexCache.Add(Key, NewIndex);
					EdgeVertex[Edge] = NewIndex;
				}

				// Triangles, with the Y-mirror's winding swap (A,C,B) -- the
				// same swap every builder in this plugin performs.
				const int8* Triangles = TriTable[CaseIndex];
				for (int32 Index = 0; Triangles[Index] != -1; Index += 3)
				{
					OutSection.Indices.Add(EdgeVertex[Triangles[Index + 0]]);
					OutSection.Indices.Add(EdgeVertex[Triangles[Index + 2]]);
					OutSection.Indices.Add(EdgeVertex[Triangles[Index + 1]]);
				}
			}
		}
	}

	if (OutSection.Indices.Num() == 0)
	{
		return false;
	}

	OutSection.Name = TEXT("isoSurface");
	OutSection.bDefaultVisible = true;
	return true;
}

bool FlowVizIsoSurface::PercentilePositiveIsoValue(
	TArrayView<const double> Values, double Percentile, double& OutIsoValue)
{
	TArray<double> Positive;
	Positive.Reserve(Values.Num());
	for (const double Value : Values)
	{
		if (FMath::IsFinite(Value) && Value > 0.0)
		{
			Positive.Add(Value);
		}
	}
	if (Positive.Num() == 0)
	{
		// A wake with no vortices has no honest default -- refuse, never invent.
		return false;
	}

	Positive.Sort();
	const double Clamped = FMath::Clamp(Percentile, 0.0, 100.0);
	const int32 Rank = FMath::Clamp(
		FMath::FloorToInt32(Clamped / 100.0 * (Positive.Num() - 1)), 0, Positive.Num() - 1);
	OutIsoValue = Positive[Rank];
	return true;
}

